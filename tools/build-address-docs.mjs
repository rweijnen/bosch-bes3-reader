#!/usr/bin/env node
// Generates docs/address-registry.md from src/address-registry.json — a human-readable
// reference, grouped by component, with a per-address table and a "worked examples" section for
// any entry that has one. The registry is the only source; this doc can never drift from what
// the code actually knows, because it's generated from the same file the app loads.
//
// Usage: node tools/build-address-docs.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const registry = JSON.parse(readFileSync(path.join(root, 'src/address-registry.json'), 'utf8'));
const { addresses, _meta } = registry;

function hex(n) {
  return '0x' + n.toString(16).padStart(4, '0');
}

function esc(s) {
  return String(s ?? '').replace(/\|/g, '\\|');
}

const byComponent = new Map();
for (const a of addresses) {
  if (!byComponent.has(a.component)) byComponent.set(a.component, []);
  byComponent.get(a.component).push(a);
}

const lines = [];
lines.push('# Bosch BES3 Address Registry — Reference');
lines.push('');
lines.push(`Generated from \`src/address-registry.json\` (registryVersion ${_meta.registryVersion}) — do not edit this file directly, edit the JSON and run \`node tools/build-address-docs.mjs\`.`);
lines.push('');
lines.push(`License: **${_meta.license}** — attribution required (${_meta.attribution}). See \`LICENSE-DATA\`.`);
lines.push('');
lines.push(`Total: ${addresses.length} addresses across ${byComponent.size} components. ${addresses.filter((a) => a.confirmed).length} confirmed against real captured data; ${addresses.filter((a) => a.kind !== 'unknown').length} have a confirmed decode kind.`);
lines.push('');
lines.push('## Contents');
lines.push('');
for (const component of [...byComponent.keys()].sort()) {
  lines.push(`- [${component}](#${component.toLowerCase()}) (${byComponent.get(component).length})`);
}
lines.push('');

const examples = addresses.filter((a) => a.example);

for (const component of [...byComponent.keys()].sort()) {
  const entries = byComponent.get(component).slice().sort((a, b) => a.address - b.address);
  const readableCount = entries.filter((e) => e.readable).length;
  lines.push(`## ${component}`);
  lines.push('');
  lines.push(`${entries.length} addresses, ${readableCount} readable.`);
  lines.push('');
  lines.push('| Address | Name | Label | Kind | R/W | Confirmed | Source |');
  lines.push('|---|---|---|---|---|---|---|');
  for (const e of entries) {
    const rw = `${e.readable ? 'R' : ''}${e.writable ? 'W' : ''}` || '—';
    lines.push(`| ${hex(e.address)} | \`${esc(e.name)}\` | ${esc(e.label)} | ${esc(e.kind)} | ${rw} | ${e.confirmed ? '✓' : ''} | ${esc(e.source)} |`);
  }
  lines.push('');
}

if (examples.length) {
  lines.push('## Worked examples');
  lines.push('');
  lines.push('Addresses with a real captured-byte walkthrough, for anything non-obvious about how to decode them.');
  lines.push('');
  for (const e of examples) {
    lines.push(`### ${e.component}.${e.name} (${hex(e.address)})`);
    lines.push('');
    if (e.notes) lines.push(esc(e.notes));
    lines.push('');
    lines.push('```');
    lines.push(`raw bytes:  ${e.example.rawBytes}`);
    lines.push(`decoded:    ${e.example.decoded.join(', ')}`);
    lines.push('```');
    lines.push('');
  }
}

const outDir = path.join(root, 'docs');
mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, 'address-registry.md');
writeFileSync(outPath, lines.join('\n') + '\n');
console.log(`Wrote ${outPath} (${addresses.length} addresses, ${examples.length} worked examples)`);
